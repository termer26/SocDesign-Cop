"""Generate explicit bindings against the pinned, unchanged upstream SoC main."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def generate():
    source = ROOT / 'vendor/e203_hbirdv2/rtl/e203/subsys/e203_subsys_main.v'
    header = source.read_text().split('module e203_subsys_main(', 1)[1].split(');', 1)[0]
    ports = re.findall(r'^\s*(input|output)\s+(\[[^\]]+\]\s*)?(\w+)', header, re.M)
    bindings = {
        'pc_rtvec': "32'ha0070000", 'test_mode': "1'b1",
        'hfextclk': 'clk', 'hfclk': 'soc_clk', 'ls_clk': 'ls_clk',
        'corerst': '!rst_n || core_hold', 'hfclkrst': '!rst_n || core_hold',
    }
    declarations = []
    for bus in ('sysper', 'sysmem'):
        for name, width in [('cmd_valid',1),('cmd_ready',1),('cmd_read',1),('cmd_addr',32),
                            ('cmd_wdata',32),('cmd_wmask',4),('rsp_valid',1),('rsp_ready',1),
                            ('rsp_err',1),('rsp_rdata',32)]:
            signal = bus + '_icb_' + name
            declarations.append(f"    wire {'['+str(width-1)+':0] ' if width>1 else ''}{signal};")
            bindings[signal] = signal
    for bus in ('aon','dm','sysfio'):
        signal = bus + '_icb_cmd_valid'
        declarations.append(f'    wire {signal};')
        bindings.update({signal:signal,bus+'_icb_cmd_ready':"1'b1",bus+'_icb_rsp_valid':signal,
                         bus+'_icb_rsp_rdata':"32'd0",bus+'_icb_rsp_err':"1'b1"})
    lines = []
    for direction,width,name in ports:
        zero="1'b0"
        if width:
            high,low=width.strip()[1:-1].split(':')
            zero="{("+high+"-("+low+")+1){1'b0}}"
        value=bindings.get(name,zero if direction=='input' else '')
        if name.startswith('io_pads_qspi0_') and direction=='input': value="1'b1"
        lines.append(f'        .{name}({value})')
    text='''`timescale 1ns/1ps
`include "e203_defines.v"
// Generated by scripts/generate_e203_wrapper.py from pinned upstream ports.
// Uses the original SoC main: CPU, native memory/peripheral fabric, CLINT/PLIC,
// GPIO/UART/SPI/I2C/timers and TCMs. External clock bypass is selected explicitly.
// AON/debug external endpoints are tied off; this is the public reference platform.
module e203_ffn_soc #(parameter integer ROWS=99, COLS=256, SRAM_WAIT=0) (
    input wire clk,ls_clk,rst_n,core_hold,
    input wire host_cmd_valid,host_cmd_read,
    output wire host_cmd_ready,
    input wire [31:0] host_cmd_addr,host_cmd_wdata,
    input wire [3:0] host_cmd_wmask,
    output wire host_rsp_valid,host_rsp_err,
    input wire host_rsp_ready,
    output wire [31:0] host_rsp_rdata,
    output wire accel_irq
);
    wire soc_clk;
    reg [1:0] reset_sync;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) reset_sync<=0; else reset_sync<={reset_sync[0],1'b1};
    wire fabric_rst_n=reset_sync[1];
'''+ '\n'.join(declarations)+'''
    e203_subsys_main u_e203 (
'''+',\n'.join(lines)+'''
    );
    wire a_cmd_valid,a_cmd_ready,a_cmd_read,a_rsp_valid,a_rsp_ready,a_rsp_err;
    wire [31:0] a_cmd_addr,a_cmd_wdata,a_rsp_rdata;
    wire [3:0] a_cmd_wmask;
    ffn_soc_peripheral #(.ROWS(ROWS),.COLS(COLS)) u_accel (
        .clk(soc_clk),.rst_n(fabric_rst_n),
        .csr_cmd_valid(sysper_icb_cmd_valid),.csr_cmd_ready(sysper_icb_cmd_ready),
        .csr_cmd_read(sysper_icb_cmd_read),.csr_cmd_addr(sysper_icb_cmd_addr),
        .csr_cmd_wdata(sysper_icb_cmd_wdata),.csr_cmd_wmask(sysper_icb_cmd_wmask),
        .csr_rsp_valid(sysper_icb_rsp_valid),.csr_rsp_ready(sysper_icb_rsp_ready),
        .csr_rsp_err(sysper_icb_rsp_err),.csr_rsp_rdata(sysper_icb_rsp_rdata),
        .mem_cmd_valid(a_cmd_valid),.mem_cmd_ready(a_cmd_ready),.mem_cmd_read(a_cmd_read),
        .mem_cmd_addr(a_cmd_addr),.mem_cmd_wdata(a_cmd_wdata),.mem_cmd_wmask(a_cmd_wmask),
        .mem_rsp_valid(a_rsp_valid),.mem_rsp_ready(a_rsp_ready),.mem_rsp_err(a_rsp_err),
        .mem_rsp_rdata(a_rsp_rdata),.irq(accel_irq));
    icb_shared_sram #(.WAIT_CYCLES(SRAM_WAIT)) u_sram (
        .clk(soc_clk),.rst_n(fabric_rst_n),
        .cmd_valid({host_cmd_valid,a_cmd_valid,sysmem_icb_cmd_valid}),
        .cmd_ready({host_cmd_ready,a_cmd_ready,sysmem_icb_cmd_ready}),
        .cmd_read({host_cmd_read,a_cmd_read,sysmem_icb_cmd_read}),
        .cmd_addr({host_cmd_addr,a_cmd_addr,sysmem_icb_cmd_addr}),
        .cmd_wdata({host_cmd_wdata,a_cmd_wdata,sysmem_icb_cmd_wdata}),
        .cmd_wmask({host_cmd_wmask,a_cmd_wmask,sysmem_icb_cmd_wmask}),
        .rsp_valid({host_rsp_valid,a_rsp_valid,sysmem_icb_rsp_valid}),
        .rsp_ready({host_rsp_ready,a_rsp_ready,sysmem_icb_rsp_ready}),
        .rsp_err({host_rsp_err,a_rsp_err,sysmem_icb_rsp_err}),
        .rsp_rdata({host_rsp_rdata,a_rsp_rdata,sysmem_icb_rsp_rdata}));
endmodule
'''
    target=ROOT/'rtl/e203_ffn_soc.sv'
    target.write_text(text,encoding='utf-8')
    print(f'Generated {len(ports)} explicit upstream port bindings: {target}')

if __name__=='__main__': generate()
